from pipeline.instances import instances
import numpy as np
import math
import copy

#########################################################################
#################   SOLVER ATO PRICING - MULTI-STAGE    #################
#########################################################################

### PARAMETERS ###

##############################################
# GENERAL SIZE #
comp = 5 # 3X, 4, 5, 6, 7X
prod = 4 # 2X, 3, 4, 5, 6X
stages = 8                     
branching = [2,2,2,2,2,2,2]   # Binary tree

# [5,5,5,2,1,1,1]
# [10,5,2,2,1,1,1]
# [20,5,2,1,1,1,1]
# [50,2,2,1,1,1,1]
# [125,2,1,1,1,1,1]

scenarios = math.prod(branching)   # 128 scenarios
##############################################


##############################################
# BILL OF MATERIALS 
# Here we have 2 options: 
#   define randomly the BoM, where products use an amount of components between [min_use, max_use]
#   or use a specific BoM defined in parameters.py (W model, N model, etc)
min_use = 3
max_use = 4
other = False
##############################################


##############################################
# PRICES
# The discrete set of prices defined by [lb_price, ub_price] in steps of step_price.
# i.e, the discrete set [30,50] in steps of 2: [30, 32, 34,..., 48, 50]
lb_price = 15
ub_price = 60
step_price = 5
##############################################


##############################################
# COSTS
# Similar to how the discrete set of prices work. Define the set [min_cost, max_cost] in steps of five 
# (the steps can be modified in params.py)
min_cost = 5
max_cost = 25
inv_factor = 0.2
# I0: quantity to satisfy expected demand at given price
# select price --> determine expected demand --> satisfy initial inventory 
I0 = np.max([lb_price, ub_price]) # Currently set to satisfy minimum expected demand (>0)
##############################################

##############################################
# MULTIPLICATIVE STOCHASTIC COMPONENT - DEMAND
# epsilon: given by a uniform distribution U[lb_epsilon, ub_epsilon]
lb_epsilon = 0.7
ub_epsilon = 1.3
##############################################
# ADDITIVE STOCHASTIC COMPONENT - DEMAND
# delta: given by a normal distribution N(mu_delta, std_delta)
mu_delta = 0
std_delta = 2
##############################################
# PRICE LINEAR EXPRESSION - DEMAND
# Decreasing linnear expression for the demand. given by: (a - b * w)
a = 100
b = 1.6
# Full demand expression given by: epsilon[t,s] * (a - b * w[j,t,p,s]) + delta[j,t,s]
##############################################

##############################################
# LEAD TIMES
# lead times are randomly generated by a uniform dist U[lb_L,ub_L]. 
# in our work we can simply change between deterministic or stochastic lead times. 
#   For deterministic: L = L[i,t]
#   For stochastic: L = L[i,t,s]
lb_L = 1
ub_L = 2
det = False # False for stochastic lead times (While we tested with deterministic, we mostly focus in stochastic)
##############################################

##############################################
# UNCERTAINTY ANALYSIS 
# We can calculate the following metrics for uncertainty analysis:
#   - VSS: Value of the Stochastic Solution
#   - EVPI: Expected Value of Perfect Information
#   - VSS_TS: Value of Stochastic Solution based on two stage model

vss_calc = False
evpi_calc = False
vss_ts_calc = False   
##############################################


##############################################
# EXPERIMENTAL SETTINGS
show_var = False   # export solution in an excel file. Can be used for fine analisys of decision behavior.
#=============================================
show_heatmap = False   # Save heatmaps to figures for every decision variable
show_boxplot = False   # Save boxplot to figures for every decision variable
show_candlestick = False   # Save candlestick to figures for every decision variable
#=============================================
show_kpis=True   # Calculate and print KPIs for fulfillment, utilization, inventory ratio and weighted average price
#=============================================
time_limit = 900 # limit for each iteration
seed = 5
iter = 2 # 1 for a single instance. >2 for several (mean results, odd number recommended)
#=============================================
#=============================================


#=============================================
#=============================================
# SPECIFIC INSTANCE CONFIGS
#=============================================
# Here we can use very specific instances from the literature. All will be detailed in params.py and generator.py
# These instances include all but stages, scenario tree and lead time distribution.
#=============================================
inst = "None"
#=============================================
# "None" -> Manual input of parameters. Beware of infeasibility!
# "Oh_et_al_1" -> Simple W model (3x2) based on Oh et al. (2014)
# "Oh_et_al_2" -> 5x4 model used by Akçay & Xu (2004) and Oh et al. (2014)
# "Oh_et_al_3" -> 11 x 11 instance based on Oh et al. (2014)
#=============================================



from data.config import (ProblemSize, BomConfig, CostConfig, PriceConfig,
                     DemandConfig, LeadTimeConfig, RunConfig, ExperimentConfig)

size = ProblemSize(inst, comp, prod, stages,
                    scenarios, branching, seed, time_limit)
bom = BomConfig(min_use, max_use, other)
costs = CostConfig(min_cost, max_cost, inv_factor, I0)
price = PriceConfig(lb_price, ub_price, step_price)
demand = DemandConfig(a, b, lb_epsilon, ub_epsilon, mu_delta, std_delta)
lead_times = LeadTimeConfig(lb_L, ub_L, det)

#=============================================
# SPECIFIC CONFIGS
#=============================================
# in this research we explore the ATO problem with several model formulations. They are detailed below.
# depending on their nature, they will be in either the models or the sol_approach folders.
#============================================
#   "MS" -> Standard multistage model (non-linear).
#============================================
#   "MS_linear" -> multistage with linealized revenue (MILP). 
#============================================
#   "MS_linear_affine" -> multistage with linealized revenue AND affine pricing policy.
#============================================
#   "Affine_eval" -> Solves MS_linear_affine, extract and approximate affine policy to binary, evaluate in MS_linear with w fixed.
#   "Relaxed_eval" -> Solve relaxed MS_linear, extract and approximate affine policy to binary, evaluate in MS_linear with w fixed.
#============================================
#   "Iterative_heuristic" -> iterative heuristic: iterates between solving pricing problem and inventory problem (features vector contains inventory levels from inventory problem)
#============================================
# Others:
#   "TS_linear" -> Two stage version of MS_linear model.
#   "TS_linear_affine" -> two-stage with linearized revenue AND affine pricing policy (x here-and-now).
#   "Relaxed_eval" ->  Relax MS_linear , extract and approximate cts policy to binary, evaluate in MS_linear with w fixed.
#============================================


run_configs = [
    RunConfig(Model="MS_linear", W_cts=True, show_kpis=show_kpis),
    # RunConfig(Model="MS_linear_affine", W_cts=False, show_fulfillment=True),
    RunConfig(Model="Relaxed_eval", show_kpis=show_kpis),
    RunConfig(Model="Affine_eval", show_kpis=show_kpis),
    RunConfig(Model="Iterative_heuristic", show_kpis=show_kpis)
]

for run in run_configs:
    current_size = copy.deepcopy(size)
    cfg = ExperimentConfig(current_size, bom, costs, price, demand, lead_times, run, iter)
    _,_ = instances(cfg)